/**
 * Exports the compiled Election contract to the Next.js app as
 * lib/contract/election.ts.
 *
 * The app deploys a fresh Election per university election, so it needs the
 * bytecode as well as the ABI. Both are emitted as `as const` TypeScript so
 * viem can infer argument and return types across the whole app.
 *
 *   npm --prefix blockchain run export
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const BLOCKCHAIN_ROOT = join(HERE, "..");
const APP_ROOT = join(BLOCKCHAIN_ROOT, "..");

const ARTIFACT = join(
  BLOCKCHAIN_ROOT,
  "artifacts",
  "contracts",
  "Election.sol",
  "Election.json",
);
const OUT_FILE = join(APP_ROOT, "lib", "contract", "election.ts");

const artifact = JSON.parse(await readFile(ARTIFACT, "utf8")) as {
  abi: unknown[];
  bytecode: string;
};

if (!artifact.bytecode || artifact.bytecode === "0x") {
  throw new Error("Election.json has no bytecode. Run `hardhat build` first.");
}

const source = `// Generated by blockchain/scripts/export-artifact.ts. Do not edit by hand.
// Re-run \`npm --prefix blockchain run export\` after changing Election.sol.

export const electionBytecode =
  "${artifact.bytecode}" as \`0x\${string}\`;

export const electionAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

await mkdir(dirname(OUT_FILE), { recursive: true });
await writeFile(OUT_FILE, source, "utf8");

console.log(`Wrote ${OUT_FILE}`);
console.log(`  ABI entries: ${artifact.abi.length}`);
console.log(`  Bytecode:    ${artifact.bytecode.length / 2 - 1} bytes`);
